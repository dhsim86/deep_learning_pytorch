# 맥북(M1 Pro / 32GB)에서 더 가볍고 빠르게 학습하기 위해 모델과 학습 설정만 교체한 버전입니다.
# 변경한 부분에는 모두 [변경] 태그를 달아두었으니 원본과 비교해서 보면 됩니다.
#
# -----------------------------------------------------------------------------------------------------
# 1. 왜 kakaocorp/kanana-2-1.3b-instruct 인가
# -----------------------------------------------------------------------------------------------------
# 기존 Konan-LLM-OND(4.08B)는 bf16으로 올리는 것만으로 8.2GB를 먹어서, MPS가 실제로 쓸 수 있는
# 메모리 예산(torch.mps.recommended_max_memory() = 22.9GB, 32GB 전부가 아님) 안에서 빠듯했습니다.
#
# 후보들을 실제로 조사/실측해서 비교한 결과입니다.
# (한국어 토큰수 = 동일한 한국어 금융 기사 236자를 각 토크나이저로 인코딩한 실측값.
#  토큰수는 학습 연산량에 그대로 비례하므로 파라미터 수만큼 중요합니다)
#
#   모델                                    파라미터   가중치(fp16)  한국어토큰수   상대 학습비용
#   ------------------------------------------------------------------------------------------
#   konantech/Konan-LLM-OND (기존)           4.08B      8.2GB          117          1.00x
#   kakaocorp/kanana-2-3b-instruct           3.51B      7.0GB           99          0.73x
#   kakaocorp/kanana-2-1.3b-instruct  <-선택  1.29B      2.6GB           99          0.27x
#   K-intelligence/Midm-2.0-Mini-Instruct    2.31B      4.6GB          103          0.50x
#   LGAI-EXAONE/EXAONE-4.0-1.2B              1.28B      2.6GB          130          0.35x
#   google/gemma-4-E2B-it                    5.12B     10.2GB          148          (아래 3번 참고)
#
#   * 상대 학습비용 = (유효 파라미터 x 한국어 토큰수) 를 기존 모델 기준으로 정규화한 값
#
# kanana-2-1.3b-instruct 를 고른 이유:
#   - 카카오가 2026-07 공개한 최신 SLM. 3B 모델을 cascade pruning + distillation 으로 압축한 모델이라
#     1.3B치고 한국어 성능이 높습니다 (KMMLU 44.17, HAE-RAE 75.34 - Qwen3-1.7B-Base 의 55.54 보다 위)
#   - 한국어 토크나이저 효율이 후보 중 최고 (2.38 chars/token). 같은 기사를 기존 모델보다 15% 적은
#     토큰으로 표현하므로, 파라미터가 작아진 것과 별개로 추가 이득이 있습니다
#   - 가중치가 2.6GB라 메모리가 완전히 여유로워집니다 -> gradient checkpointing을 꺼서 속도를 더 벌 수 있음
#   - 3:1 비율로 sliding window attention(window 1024) 과 full attention 을 섞은 하이브리드 구조라
#     긴 컨텍스트에서도 KV 캐시가 가볍습니다 (최대 32K 지원)
#
# 주의: Kanana2TinyForCausalLM 은 transformers 가 기본 내장하지 않은 커스텀 아키텍처입니다.
#      그래서 from_pretrained 에 trust_remote_code=True 가 반드시 필요합니다 (= 허깅페이스 저장소의
#      modeling_kanana2_tiny.py 를 내려받아 실행). 원격 코드 실행이라는 점은 감안하고 쓰세요.
#      다행히 해당 파일에는 transformers 버전차를 흡수하는 호환 shim이 들어있어 5.14.1에서도 동작합니다.
#
# -----------------------------------------------------------------------------------------------------
# 2. LoRA 설정은 왜 그대로 두는가
# -----------------------------------------------------------------------------------------------------
# Kanana2TinyAttention 의 모듈 이름이 q_proj / k_proj / v_proj / o_proj 로 Qwen3와 동일합니다.
# 따라서 기존 target_modules=["q_proj", "v_proj"] 가 그대로 먹습니다. LoRA 설정은 손대지 않았습니다.
# (실제로 붙여보면 학습 대상 파라미터 1,966,080개 = 전체의 0.152%)
#
# -----------------------------------------------------------------------------------------------------
# 3. google/gemma-4-E2B-it 은 왜 쓰지 않았는가
# -----------------------------------------------------------------------------------------------------
# 파인튜닝 자체는 가능합니다. transformers 5.14.1이 gemma4를 지원하고 Gemma4ForCausalLM 클래스도 있으며,
# q_proj / v_proj 모듈명도 같아서 현재 LoRA 설정이 그대로 적용됩니다. 하지만 목적에 정반대입니다.
#
#   - "E2B"의 E는 effective(유효)입니다. 실제 파라미터는 5.12B이고 bf16으로 10.2GB로,
#     줄이려던 기존 모델(4.08B / 8.2GB)보다 오히려 무겁습니다.
#     이 중 약 2.35B(4.7GB)가 PLE(Per-Layer Embeddings) 테이블입니다.
#     (vocab_size_per_layer_input 262144 x hidden_size_per_layer_input 256 x 35 layers)
#     추론 때는 단순 lookup이라 "유효 2.3B"로 동작하지만, 학습 때는 메모리에 그대로 올라갑니다.
#   - 한국어 토크나이저가 후보 중 최악입니다 (1.59 chars/token). 같은 기사가 kanana-2로는 99토큰인데
#     gemma-4는 148토큰이라 50% 더 많은 연산을 합니다.
#   - AutoModelForCausalLM 이 Gemma4ForConditionalGeneration 으로 매핑돼서 텍스트 전용 학습인데도
#     vision 인코더(~150M) + audio 인코더(~300M)까지 같이 로드됩니다.
#     텍스트만 쓰려면 Gemma4ForCausalLM 을 직접 import 해야 하는 코드 수정이 추가로 필요합니다.
#
# -----------------------------------------------------------------------------------------------------
# 4. M1 Pro 에서의 학습 속도 최적화 (이 파일에 반영된 것)
# -----------------------------------------------------------------------------------------------------
# 이 맥북에서 직접 측정한 값들입니다.
#
#   [a] bf16 -> fp16 : M1 Pro GPU에는 bfloat16 연산 유닛이 없어서 에뮬레이션으로 처리됩니다.
#       MPS matmul 2048x2048 :  fp16 4.55 TFLOPS  /  bf16 2.29 TFLOPS   (bf16이 딱 절반)
#       -> torch_dtype 과 SFTConfig 의 정밀도 플래그를 fp16으로 바꿨습니다.
#       -> 단 CUDA(A100/RTX30xx 이상)에서는 bf16이 정석이므로, 플랫폼별로 분기시켰습니다.
#       -> fp16은 표현 범위가 좁아 오버플로 위험이 있지만, 이 모델+LoRA 조합으로 실제 학습 스텝을
#          돌려서 loss / gradient 에 NaN이 없는 것을 확인했습니다.
#
#   [b] gradient_checkpointing 끄기 : 메모리를 아끼는 대신 forward를 두 번 계산하는 옵션입니다.
#       1.3B 모델은 가중치가 2.6GB뿐이라 22.9GB 예산에 충분히 들어가므로 끄는 게 이득입니다.
#       HF Trainer + LoRA 로 측정: 켰을 때 3.89s / 껐을 때 2.26s (약 1.7배)
#       (단 이 수치는 kanana-2 본체가 아니라 6층짜리 작은 테스트 모델로 잰 값이라 배율만 참고하세요)
#       -> MPS에서만 끄고, CUDA(QLoRA)에서는 켠 상태를 유지합니다.
#
#   [c] attn_implementation="sdpa" : 명시하지 않으면 구현이 바뀔 수 있어서 못박아 두었습니다.
#
#   [a]+[c] 를 실제 kanana-2-1.3b + LoRA 로 이 맥북에서 측정한 값 (배치1, seq 1200, fwd+bwd 1스텝):
#
#       dtype      attention     ms/step      비고
#       ----------------------------------------------------------
#       fp16       sdpa            5,942      <- 이 파일이 쓰는 조합
#       fp16       eager           7,354
#       bf16       sdpa            8,155
#       bf16       eager          14,541      <- 가장 느림
#
#       즉 정밀도와 attention 구현만 바꿔도 2.45배 차이가 납니다.
#       이때 MPS 메모리 사용량은 3.36GB로, 22.9GB 예산에 한참 여유가 있습니다.
#
# 검토했지만 적용하지 않은 것:
#   - collate_fn 안의 토크나이징을 사전 계산으로 빼기 -> 전체 3 epoch 통틀어 6초라 무의미
#   - MLX(mlx-lm)로 갈아타기 -> Apple Silicon에서 더 빠르지만 PyTorch 학습용 레포라 취지에 안 맞음
#
# -----------------------------------------------------------------------------------------------------
# 5. 실제로 이 스크립트를 돌려본 결과 (max_steps=3 으로 줄여서 3 step만 확인)
# -----------------------------------------------------------------------------------------------------
#   loss           : 1.119 -> 1.234 -> 0.9026   (NaN 없이 정상적으로 내려감)
#   grad_norm      : 2.285 / 2.353 / 2.264      (폭발하지 않고 안정적)
#   token accuracy : 0.727 / 0.701 / 0.787
#   MPS 메모리      : 3.36GB (예산 22.9GB)
#
# 전체 학습 시간은 대략 3~4시간으로 예상합니다.
# (훈련 793개 x 3 epoch / 실질배치 4 = 약 595 step. 다만 초반 몇 step은 MPS 커널 컴파일 때문에
#  편차가 크게 나타나므로 - 실제로 1step 62초, 2step 105초, 3step 14초로 들쭉날쭉했습니다 -
#  정확한 시간은 어느 정도 돌려봐야 알 수 있습니다)
#
# 더 줄이고 싶으면 메모리가 남으므로 per_device_train_batch_size 를 2~4로 올리고
# gradient_accumulation_steps 를 그만큼 나눠서 실질 배치 크기를 유지하는 방법이 있습니다.
# (그 경우 배치 안에서 패딩 낭비가 생기므로 group_by_length=True 를 같이 켜는 게 좋습니다)
