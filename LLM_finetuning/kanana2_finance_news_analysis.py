    ## 왜 필요? 딥러닝은 역전파에 쓰려고 중간 계산값을 전부 메모리에 들고 있는데, 8B급 모델에서는 이게 VRAM을 엄청나게 잡아먹음
    ##          이 옵션을 켜면 메모리를 크게(수십 %) 아끼는 대신 재계산 때문에 학습 속도가 대략 20~30% 느려짐
    ## 큰 모델을 소비자용/단일 GPU에서 학습할 때는 사실상 필수 옵션 (SFTConfig 기본값도 True)
    ## [변경] True 고정 -> CUDA에서만 True, 맥북(MPS)에서는 False
    ##        이 옵션은 "메모리를 아끼는 대신 forward를 두 번 계산"하는 트레이드오프입니다.
    ##        기존 4B 모델일 때는 켜는 게 필수였지만, 1.3B로 내려오면서 가중치가 2.6GB밖에 안 되고
    ##        학습 중 MPS 메모리 실측이 3.36GB(예산 22.9GB)라 메모리를 아낄 이유가 사라졌습니다.
    ##        끄면 재계산이 없어져 그만큼 빨라집니다. (HF Trainer + LoRA 실측: 켜면 3.89s / 끄면 2.26s)
    ##        CUDA 쪽은 QLoRA로 더 큰 모델을 돌릴 수 있으므로 기존대로 True를 유지합니다.
    gradient_checkpointing=torch.cuda.is_available(),

