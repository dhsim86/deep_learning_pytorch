    ##    M1 Pro의 GPU에는 bfloat16 전용 연산 유닛이 없어서 bf16이 에뮬레이션으로 처리됩니다.
    ##    그래서 애플 실리콘에서는 "안정성이 좋은 bf16"이라는 통념이 성립하지 않고, 그냥 느리기만 합니다.
    ##      - MPS matmul 2048x2048 실측 : fp16 4.55 TFLOPS vs bf16 2.29 TFLOPS (bf16이 딱 절반)
    ##      - 이 모델 + LoRA 로 실제 학습 스텝 실측 : fp16 5,942ms vs bf16 8,155ms
    ##    fp16은 표현 범위가 좁아 오버플로/언더플로 위험이 있는 것이 맞지만,
    ##    이 모델+LoRA 조합으로 실제 스텝을 돌려 loss와 gradient에 NaN이 없는 것을 확인했습니다.
    ##    (혹시 학습 중 loss가 nan으로 튀면 이 줄을 bfloat16으로 되돌리면 됩니다)
    ##
    ## 2) attn_implementation="sdpa"
    ##    PyTorch 내장 scaled_dot_product_attention 을 쓰라고 명시하는 옵션입니다.
    ##    지정하지 않으면 모델/버전에 따라 느린 eager 구현이 선택될 수 있습니다.
    ##    실측 : sdpa 5,942ms vs eager 7,354ms
    ##    (참고로 CUDA에서 흔히 쓰는 flash_attention_2 는 MPS에서 사용할 수 없습니다)
    ##
    ## 3) trust_remote_code=True
    ##    위 tokenizer 와 같은 이유. Kanana2TinyForCausalLM 이 transformers 내장이 아니기 때문입니다.
    model = AutoModelForCausalLM.from_pretrained(
        model_id,
        torch_dtype=torch.float16 if use_mps else torch.bfloat16, # CPU로 떨어지면 기존대로 bfloat16
        attn_implementation="sdpa",
        trust_remote_code=True,
    )

