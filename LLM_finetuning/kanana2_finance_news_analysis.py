    ## 왜 필요? GPU 메모리(VRAM) 사용량을 결정하는 가장 큰 요인. 값이 크면 학습이 안정적이고 빠르지만 메모리가 터짐(OOM)
    ##          8B 모델 + 긴 뉴스 텍스트 조합이라 2 정도로 아주 작게 잡은 것 (OOM이 나면 1로 줄이면 됨)
