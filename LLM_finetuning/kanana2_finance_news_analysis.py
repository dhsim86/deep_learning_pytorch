    ## 왜 필요? 데이터를 한 번만 보면 모델이 패턴을 충분히 못 익힘(과소적합). 반대로 너무 많이 돌리면
    ##          훈련 데이터를 통째로 외워버려서 처음 보는 뉴스에는 오히려 성능이 떨어짐(과적합)
